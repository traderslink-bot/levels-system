// Focused offline checks of actual runtime methods; no provider or network calls.
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const ts = require(process.argv[2] || 'typescript');
const source = fs.readFileSync(path.join(__dirname, '../src/lib/monitoring/manual-watchlist-runtime-manager.ts'), 'utf8');
const ast = ts.createSourceFile('manager.ts', source, ts.ScriptTarget.Latest, true);
const cls = ast.statements.find(n => ts.isClassDeclaration(n) && n.name?.text === 'ManualWatchlistRuntimeManager');
const methods = ['getTradersLinkAiReadPublicationPreview', 'buildTraderNotesCard', 'saveTraderNotes'];
const extracted = methods.map(name => { const m = cls.members.find(n => n.name?.getText(ast) === name); assert.ok(m); return m.getText(ast); }).join('\n');
const compiled = ts.transpileModule(`class Selected {${extracted}}`, { compilerOptions: { target: ts.ScriptTarget.ES2022 }, reportDiagnostics: true });
assert.equal(compiled.diagnostics.filter(d => d.category === ts.DiagnosticCategory.Error).length, 0);
const Selected = new Function('currentDiscordAudience', 'renderApprovedAnalysisDiscord', 'publicationPreviewHash', 'normalizeSymbol', compiled.outputText + ';return Selected;')(() => ({}), () => [], () => 'hash', s => s.toUpperCase());
(async () => {
  const m = new Selected(); let notes = 'Exact owner notes\n<plain text>'; let sends = [];
  const analysis = { symbol: 'GYGY', generationId: 'saved' };
  let review = { cycleId: 'cycle', head: 2, draft: { revision: 2, body: { kind: 'original', payload: analysis } }, events: [] };
  m.options = { now: () => 123 };
  m.getTradersLinkAiReadReview = () => review;
  m.watchlistStore = { getEntry: () => ({ active: true, publicationReview: { cycleId: 'cycle' }, traderNotesDraft: notes }), patchEntry: (symbol, patch) => { assert.equal(symbol, 'GYGY'); notes = patch.traderNotesDraft; } };
  m.buildReviewedWebsitePatch = () => ({ symbol: 'GYGY', cards: { tradersLinkAiRead: analysis, levelMap: { body: 'levels' } } });
  m.persistWatchlist = () => {};
  m.liveWatchlistPublisher = { publish: async patch => sends.push(patch) };
  const initial = m.getTradersLinkAiReadPublicationPreview('GYGY').publication;
  assert.equal(initial.website.cards.traderNotes.body, notes);
  assert.equal(initial.website.cards.tradersLinkAiRead, analysis);
  assert.equal(initial.website.cards.levelMap.body, 'levels');
  notes = '   '; assert.equal(m.getTradersLinkAiReadPublicationPreview('GYGY').publication.website.cards.traderNotes, null);
  notes = 'New private edit';
  review.approved = { body: { kind: 'approve', draftRevision: 2, publication: initial } };
  const builder = m.buildReviewedWebsitePatch;
  m.buildReviewedWebsitePatch = () => { throw Error('Frozen retry must not rebuild'); };
  assert.equal(m.getTradersLinkAiReadPublicationPreview('GYGY').publication, initial);
  assert.equal(initial.website.cards.traderNotes.body, 'Exact owner notes\n<plain text>');
  m.buildReviewedWebsitePatch = builder; delete review.approved;
  review.events.push({ body: { kind: 'delivery', channel: 'website', status: 'acknowledged' } });
  assert.equal('traderNotes' in m.getTradersLinkAiReadPublicationPreview('GYGY').publication.website.cards, false);
  review.events = []; review.preserveExistingPublication = true;
  assert.equal('traderNotes' in m.getTradersLinkAiReadPublicationPreview('GYGY').publication.website.cards, false);
  await m.saveTraderNotes({ symbol: 'GYGY', cycleId: 'cycle', text: notes, publish: false, actor: 'owner' }); assert.equal(sends.length, 0);
  await m.saveTraderNotes({ symbol: 'GYGY', cycleId: 'cycle', text: notes, publish: true, actor: 'owner' });
  assert.equal(sends.length, 1); assert.deepEqual(Object.keys(sends[0].cards), ['traderNotes']); assert.equal(sends[0].cards.traderNotes.body, notes);
  assert.equal(sends[0].symbol, 'GYGY'); assert.equal(initial.website.cards.tradersLinkAiRead, analysis);
  console.log('PASS initial notes/analysis/levels, empty notes, frozen retry, both listed states, private save, notes-only publish');
})().catch(error => { console.error(error); process.exitCode = 1; });
